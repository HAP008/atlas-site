/**
 * scripts/licences.ts: licence report for everything the site ships, and the NOTICES file.
 *
 *   npm run licences         writes ./NOTICES
 *   npm run licences:check   fails if a licence isn't on the allow-list or NOTICES is out of date (CI)
 *
 * "Production tree" = every package `npm ci --omit=dev` installs (from package-lock.json).
 * That is a superset of what ends up in the browser, so nothing shipped can be missed.
 * Two build-only CSS packages are added by hand because their output ships: tailwindcss and shadcn.
 * The font (Newsreader) is listed too.
 *
 * If a new dependency has an unknown or copyleft licence, CI fails here until someone decides.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const NOTICES_PATH = join(ROOT, "NOTICES");

const ALLOWED = new Set([
  "MIT",
  "ISC",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "CC0-1.0",
  "CC-BY-4.0",
  "BlueOak-1.0.0",
  "Unlicense",
]);

/**
 * Not shipped: sharp and libvips are Next's server-side image optimiser. This site is a static
 * export with image optimisation off (next.config.ts), so none of it reaches ./out.
 * They are LGPL, which is why they are listed here instead of on the allow-list.
 */
const BUILD_ONLY = /^(sharp|@img\/sharp(-|$))/;

/** Shipped packages that aren't in "dependencies" because only their generated CSS ships. */
const BUILD_TIME_SHIPPED = ["tailwindcss", "shadcn"];

/** Direct dependencies whose full licence text is reproduced in NOTICES. */
const FULL_TEXT = ["next", "react", "react-dom", "radix-ui", "lucide-react", "class-variance-authority", "cn", "tailwindcss", "shadcn"];

type Pkg = { name: string; version: string; licence: string; repo: string; shipped: boolean };

function readJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, "utf8")) as Record<string, unknown>;
}

function collect(): Pkg[] {
  // Only package-lock.json is read here, so the result is identical on every machine
  // (node_modules differs by platform: macOS and the Linux CI runner install different binaries).
  const lock = readJson(join(ROOT, "package-lock.json"));
  const packages = lock.packages as Record<string, { version?: string; dev?: boolean; license?: string }>;
  const seen = new Map<string, Pkg>();
  for (const [path, meta] of Object.entries(packages)) {
    if (!path) continue;
    const name = path.replace(/^.*node_modules\//, "");
    if (meta.dev && !BUILD_TIME_SHIPPED.includes(name)) continue;
    const version = String(meta.version ?? "?");
    seen.set(`${name}@${version}`, {
      name,
      version,
      licence: String(meta.license ?? "UNKNOWN"),
      repo: `https://www.npmjs.com/package/${name}/v/${version}`,
      shipped: !BUILD_ONLY.test(name),
    });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function licenceText(name: string): string {
  const dir = join(ROOT, "node_modules", name);
  const file = ["LICENSE", "LICENSE.md", "license.md", "LICENSE.txt", "license"].map((f) => join(dir, f)).find(existsSync);
  return file ? readFileSync(file, "utf8").trim() : "(licence file not found in the package)";
}

function render(pkgs: Pkg[]): string {
  const shipped = pkgs.filter((p) => p.shipped);
  const buildOnly = pkgs.filter((p) => !p.shipped);
  const row = (p: Pkg) => `${p.name}@${p.version} | ${p.licence} | ${p.repo || "-"}`;
  return [
    "ATLAS website: third-party notices",
    "==================================",
    "",
    "Generated by scripts/licences.ts from package-lock.json. Do not edit by hand:",
    "run `npm run licences` after changing dependencies.",
    "",
    "This covers the website only. The ATLAS Mac app has its own notices in its own repository.",
    "",
    "1. Font",
    "-------",
    "Newsreader | SIL Open Font License 1.1 | https://github.com/productiontype/Newsreader",
    "Copyright 2020 The Newsreader Project Authors. Served from this site (self-hosted).",
    "Licence text: https://openfontlicense.org/open-font-license-official-text/",
    "",
    `2. Packages in the production tree (${shipped.length})`,
    "-----------------------------------------",
    "name@version | licence | source",
    ...shipped.map(row),
    "",
    `3. Installed for the build only, not shipped (${buildOnly.length})`,
    "---------------------------------------------------",
    "Next.js's server-side image optimiser. This site is a static export with image",
    "optimisation switched off, so none of this code is in the published site.",
    ...buildOnly.map(row),
    "",
    "4. Licence texts of direct dependencies",
    "---------------------------------------",
    ...FULL_TEXT.flatMap((name) => ["", `--- ${name} ---`, licenceText(name)]),
    "",
  ].join("\n");
}

const pkgs = collect();
const problems = pkgs
  .filter((p) => p.shipped && !ALLOWED.has(p.licence))
  .map((p) => `${p.name}@${p.version}: licence "${p.licence}" is not on the allow-list`);
const text = render(pkgs);
const check = process.argv.includes("--check");

if (check) {
  const current = existsSync(NOTICES_PATH) ? readFileSync(NOTICES_PATH, "utf8") : "";
  if (current !== text) problems.push("NOTICES is out of date. Run `npm run licences` and commit the result.");
} else {
  writeFileSync(NOTICES_PATH, text);
}

if (problems.length) {
  process.stderr.write(`licences FAILED\n${problems.map((p) => `  ✗ ${p}`).join("\n")}\n`);
  process.exit(1);
}
const counts = new Map<string, number>();
for (const p of pkgs.filter((x) => x.shipped)) counts.set(p.licence, (counts.get(p.licence) ?? 0) + 1);
process.stdout.write(
  `licences OK: ${pkgs.filter((p) => p.shipped).length} packages (${[...counts].map(([l, n]) => `${l} ${n}`).join(", ")}); ${pkgs.filter((p) => !p.shipped).length} build-only${check ? "; NOTICES is current" : "; NOTICES written"}\n`,
);
